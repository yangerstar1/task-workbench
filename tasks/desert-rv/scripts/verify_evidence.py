def require(ok, message):
    if not ok:
        raise ValueError(message)


def safe(path):
    path = Path(path)
    require(path.is_file() and not path.is_symlink(), 'Missing or linked evidence file')
    require(not any(p.is_symlink() for p in path.parents), 'Linked evidence ancestor')
    return path


def sha(path):
    h = hashlib.sha256()
    with safe(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def read_json(path):
    path = safe(path)
    require(path.stat().st_size <= 4 * 1024**2, 'JSON evidence exceeds size limit')
    def unique(pairs):
        result = {}
        for key, value in pairs:
            require(key not in result, 'Duplicate JSON field')
            result[key] = value
        return result
    return json.loads(path.read_text(), object_pairs_hook=unique)


def identity():
    commit = os.environ['GITHUB_SHA']
    require(re.fullmatch('[a-f0-9]{40}', commit), 'Invalid commit identity')
    actual = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    require(actual == commit, 'Checkout commit differs from run')
    run, attempt = os.environ['GITHUB_RUN_ID'], os.environ['GITHUB_RUN_ATTEMPT']
    require(re.fullmatch('[1-9][0-9]*', run) and re.fullmatch('[1-9][0-9]*', attempt), 'Invalid run identity')
    return dict(repository=REPOSITORY, commit=commit, runId=run, runAttempt=attempt,
                editorVersion=VERSION, exportManifestSha256=sha(TASK / 'PUBLIC-EXPORT.json'),
                sourceStateSha256=sha(TASK / 'SOURCE-STATE.json'), scope=SCOPE)


# PUBLIC-EXPORT is immutable historical provenance. SOURCE-STATE inventories the
# reviewed current source, not a claim that new work came from the private source.
BASELINE_EXPORT_SHA = '003d3ba2c39fc626e85053371a7b454358a35f291d5a82e30ff5be1999aec2f9'
BASELINE_COMMIT = '6dc675517db262c72dcb8c1507239d4bf10acc5d'
SOURCE_ROOTS = ('tasks/desert-rv/unity', 'tasks/desert-rv/backup-assets', 'tasks/desert-rv/scripts', 'tasks/desert-rv/art/import-candidate', 'tasks/desert-rv/art/journey-preparation')
SOURCE_FILES = ('tasks/desert-rv/ASSET-NOTICES.md', '.github/workflows/desert-rv-android.yml', '.github/workflows/desert-rv-environment.yml', '.github/workflows/desert-rv-candidate-art-import.yml', '.github/workflows/desert-rv-supplies.yml', 'tasks/desert-rv/art/reload-audio/generated-candidate.json', '.github/actions/desert-rv-rendered/action.yml', '.github/workflows/desert-rv-rendered-smoke.yml', '.github/workflows/desert-rv-player-smoke.yml', '.github/workflows/desert-rv-journey-prepare.yml', '.github/workflows/desert-rv-player-observe.yml', '.github/workflows/desert-rv-journey-rebuild.yml', '.github/workflows/desert-rv-tracer-shader-prepare.yml', '.github/workflows/desert-rv-interaction-reachability.yml')
FONT_PATH = 'tasks/desert-rv/unity/Assets/DesertRV/UI/Fonts/NotoSansCJKsc-Regular.otf'
FONT_SHA = 'a6a530f3e7e7a2c299470c42efff2e109fcc0a5be92686b96d5e84a05f3ecb2b'


def source_inventory():
    names = set(SOURCE_FILES)
    for directory in SOURCE_ROOTS:
        base = ROOT / directory
        require(base.is_dir() and not base.is_symlink(), 'Missing or linked source root')
        for path in base.rglob('*'):
            require(not path.is_symlink(), 'Linked source path')
            if path.is_file():
                # Python bytecode generated by the validator is never Unity input.
                if directory in ('tasks/desert-rv/scripts', 'tasks/desert-rv/art/import-candidate', 'tasks/desert-rv/art/journey-preparation') and '__pycache__' in path.relative_to(base).parts:
                    continue
                names.add(path.relative_to(ROOT).as_posix())
    # Exactly one reviewed deterministic restoration; never a wildcard exemption.
    if FONT_PATH in names:
        font = ROOT / FONT_PATH
        require(sha(font) == FONT_SHA and font.stat().st_size == 16437340, 'Restored font differs')
        names.remove(FONT_PATH)
    return names


def verify_source_state():
    state = read_json(TASK / 'SOURCE-STATE.json')
    require(state.get('schema') == 'desert-rv-source-state/v1', 'Unknown source-state schema')
    require(state.get('baselineGameCommit') == BASELINE_COMMIT, 'Wrong public baseline')
    require(state.get('baselineExportManifestSha256') == BASELINE_EXPORT_SHA == sha(TASK / 'PUBLIC-EXPORT.json'), 'Historical export manifest changed')
    require(state.get('coverageRoots') == list(SOURCE_ROOTS) and state.get('coverageFiles') == list(SOURCE_FILES), 'Source coverage cannot be weakened')
    require(state.get('restoredFiles') == [dict(path=FONT_PATH, sha256=FONT_SHA, size=16437340)], 'Invalid restoration exception')
    entries = state.get('files')
    require(type(entries) is list and len(entries) > 0, 'Nonempty current source inventory required')
    names = set()
    for entry in entries:
        require(type(entry) is dict and set(entry) == {'path', 'sha256', 'size'}, 'Invalid source entry fields')
        name = entry['path']
        require(type(name) is str and name not in names and not name.startswith('/') and
                '..' not in Path(name).parts and Path(name).as_posix() == name, 'Invalid or duplicate source path')
        require(type(entry['size']) is int and entry['size'] >= 0 and
                type(entry['sha256']) is str and re.fullmatch('[a-f0-9]{64}', entry['sha256']), 'Invalid source digest or size')
        names.add(name)
    require(names == source_inventory(), 'Current source inventory differs: missing or unlisted source')
    for entry in entries:
        path = ROOT / entry['path']
        require(sha(path) == entry['sha256'] and safe(path).stat().st_size == entry['size'], 'Current source bytes differ')
    return state


def guard():
    require(os.environ.get('GITHUB_ACTIONS') == 'true', 'GitHub Actions required')
    require(os.environ.get('RUNNER_ENVIRONMENT') == 'github-hosted' and os.environ.get('RUNNER_OS') == 'Linux', 'Standard hosted Linux required')
    if os.environ.get('GITHUB_EVENT_NAME') != 'workflow_dispatch':
        if os.environ.get('GITHUB_REF') == 'refs/heads/journey-interaction-reachability-ecd3':
            import journey_interaction_reachability
            journey_interaction_reachability.dispatch()
        elif os.environ.get('GITHUB_REF') == 'refs/heads/journey-tracer-shader-fix-6648':
            import journey_tracer_dispatch
            journey_tracer_dispatch.verify(ROOT, os.environ)
        else:
            import journey_rebuild_dispatch
            journey_rebuild_dispatch.verify(ROOT, os.environ)  # Existing fixed recovery request remains unchanged.
    require(os.environ.get('GITHUB_REPOSITORY') == REPOSITORY and (os.environ.get('GITHUB_REF') == 'refs/heads/main' or
            os.environ.get('GITHUB_EVENT_NAME') == 'push' and os.environ.get('GITHUB_REF') in ('refs/heads/journey-linux-export-recovery-938', 'refs/heads/journey-tracer-shader-fix-6648', 'refs/heads/journey-interaction-reachability-ecd3')), 'Trusted repository/ref required')
    require(os.environ.get('GITHUB_ACTOR') == OWNER and os.environ.get('GITHUB_TRIGGERING_ACTOR') == OWNER, 'Owner dispatch and owner rerun required')
    repo = read_json(os.environ['GITHUB_EVENT_PATH'])['repository']
    require(repo.get('full_name') == REPOSITORY and repo.get('private') is False and repo.get('fork') is False and repo.get('default_branch') == 'main', 'Public original repository required')
    identity()
    verify_source_state()
    version = safe(PROJECT / 'ProjectSettings/ProjectVersion.txt').read_text()
    require(('m_EditorVersion: ' + VERSION) in version.splitlines(), 'Unity version must match pinned editor')
    # Never accept a checked-in binary as this run\'s output.
    for directory in [TASK / 'build', TASK / 'evidence', TASK / 'artifacts', PROJECT / 'build']:
        require(not directory.exists(), 'Output directory already exists before native execution')
    print('Trusted source/run and clean native output paths verified.')


def expected_cases(mode='editmode'):
    require(mode in {'editmode', 'playmode'}, 'Unknown test mode')
    filename = 'expected_test_cases.json' if mode == 'editmode' else 'expected_playmode_test_cases.json'
    names = read_json(TASK / 'scripts' / filename)
    require(isinstance(names, list) and len(names) >= 1 and len(names) == len(set(names)), 'Invalid fixed test inventory')
    return set(names)


def inspect_tests(directory, mode='editmode'):
    reports = []
    paths = list(Path(directory).rglob('*.xml'))
    require(len(paths) <= 20, 'Too many XML files')
    for path in paths:
        require(safe(path).stat().st_size <= 10 * 1024**2, 'Oversized test report')
        root = ET.parse(path).getroot()
        if root.tag == 'test-run':
            reports.append((path, root))
    require(len(reports) == 1, 'Exactly one native NUnit test-run report required')
    path, root = reports[0]
    cases = list(root.iter('test-case'))
    names = [c.get('fullname') for c in cases]
    expected = expected_cases(mode)
    require(len(names) == len(expected) and set(names) == expected, 'Native test inventory mismatch, empty, omitted or duplicated cases')
    # Reconstruct only reviewed names and enum statuses. Never publish stdout,
    # stack traces, environment fields or native result attachments.
    allowed = {'Passed', 'Failed', 'Skipped', 'Inconclusive'}
    summary = [dict(name=c.get('fullname'), result=c.get('result') if c.get('result') in allowed else 'Unknown') for c in cases]
    evidence = TASK / ('evidence/tests' if mode == 'editmode' else 'evidence/playmode')
    evidence.mkdir(parents=True, exist_ok=True)
    result = dict(identity(), schema='desert-rv-tests/v2', testMode=mode, originalXmlSha256=sha(path),
                  cases=summary, passed=sum(c['result'] == 'Passed' for c in summary),
                  verdict='COLLECTED_NOT_YET_VERIFIED')
    (evidence / 'test-results.json').write_text(json.dumps(result, indent=2) + '\n')
    require(root.get('result') == 'Passed' and all(c['result'] == 'Passed' for c in summary), 'Native run failed or skipped tests')
    require(int(root.get('total', '-1')) == len(expected) and int(root.get('passed', '-1')) == len(expected) and int(root.get('failed', '-1')) == 0 and int(root.get('skipped', '0')) == 0 and int(root.get('inconclusive', '0')) == 0, 'Native NUnit counts mismatch')
    result['verdict'] = 'PASSED'
    (evidence / 'test-results.json').write_text(json.dumps(result, indent=2) + '\n')
    return result



def inspect_apk_bytes(apk):
    apk = safe(apk)
    require(1024**2 < apk.stat().st_size <= 1024**3, 'APK byte size outside bounds')
    with zipfile.ZipFile(apk) as archive:
        infos = archive.infolist()
        names = [item.filename for item in infos]
        require(len(infos) <= 30000 and len(names) == len(set(names)), 'APK inventory invalid')
        require(sum(item.file_size for item in infos) <= 3 * 1024**3, 'APK uncompressed payload exceeds bound')
        require(all(not name.startswith('/') and '..' not in Path(name).parts for name in names), 'Unsafe APK member path')
        required = {'AndroidManifest.xml', 'classes.dex', 'lib/arm64-v8a/libil2cpp.so', 'lib/arm64-v8a/libunity.so'}
        require(required <= set(names), 'Missing Android/ARM64 IL2CPP contents')
        require(not any(name.startswith('lib/') and not name.startswith('lib/arm64-v8a/') and not name.endswith('/') for name in names), 'Unexpected non-ARM64 native library')
        require(archive.testzip() is None, 'APK ZIP CRC mismatch')
    return dict(apkSha256=sha(apk), apkBytes=apk.stat().st_size)



def inspect_receipt(data, base, apk_result):
    expected = dict(schemaVersion=1, status='succeeded', stage='complete',
        scope='traversal-test-only-no-combat-not-complete-game', project='desert-rv/unity',
        scene='Assets/DesertRV/Scenes/TraversalHarness.unity', unityVersion=VERSION,
        version='0.1.0-dev.' + base['commit'][:12], commit=base['commit'],
        runId=base['runId'], runAttempt=base['runAttempt'],
        buildIdentitySha256=hashlib.sha256((base['commit'] + ':' + base['runId'] + ':' + base['runAttempt']).encode()).hexdigest(),
        target='Android', architecture='ARM64', backend='IL2CPP', development=True,
        signing='debug-only', apk='DesertRV.apk',
        sceneSha256=sha(PROJECT / 'Assets/DesertRV/Scenes/TraversalHarness.unity'),
        referenceSceneSha256=sha(PROJECT / 'Assets/DesertRV/Scenes/BodyStudy.unity'),
        fontSha256='a6a530f3e7e7a2c299470c42efff2e109fcc0a5be92686b96d5e84a05f3ecb2b',
        **apk_result)
    require(type(data) is dict and set(data) == set(expected), 'Native receipt fields differ from allowlist')
    require(all(type(data[k]) is type(v) and data[k] == v for k, v in expected.items()), 'Native receipt identity/configuration/hash mismatch')
    require(sha(PROJECT / 'Assets/DesertRV/UI/Fonts/NotoSansCJKsc-Regular.otf') == expected['fontSha256'], 'Restored font changed')
    return expected


def verify_upstream_identity(base):
    # Re-running only a failed downstream job must not combine native evidence
    # from an older attempt with this attempt's new build receipt.
    fields = {'COMMIT': 'commit', 'RUN_ID': 'runId', 'RUN_ATTEMPT': 'runAttempt',
              'SOURCE_STATE_SHA256': 'sourceStateSha256'}
    for mode in ('EDITMODE', 'PLAYMODE'):
        for suffix, key in fields.items():
            require(os.environ.get('EXPECTED_' + mode + '_' + suffix) == base[key],
                    'Upstream ' + mode + ' identity mismatch; rerun all jobs')


def verify_apk():
    base = identity()
    verify_upstream_identity(base)
    count = os.environ['EXPECTED_TEST_COUNT']
    xml_hash = os.environ['EXPECTED_TEST_XML_SHA256']
    require(count == str(len(expected_cases())) and re.fullmatch('[a-f0-9]{64}', xml_hash), 'Missing successful test-job identity')
    play_count = os.environ['EXPECTED_PLAYMODE_TEST_COUNT']
    play_hash = os.environ['EXPECTED_PLAYMODE_TEST_XML_SHA256']
    require(play_count == str(len(expected_cases('playmode'))) and re.fullmatch('[a-f0-9]{64}', play_hash), 'Missing successful PlayMode-job identity')
    directory = TASK / 'build/android-traversal-harness'
    apk = directory / 'DesertRV.apk'
    receipt = directory / 'build-receipt.json'
    result = inspect_apk_bytes(apk)
    native = inspect_receipt(read_json(receipt), base, result)
    # Do not tolerate reauthoring source assets during this build.
    subprocess.check_call(['git', 'diff', '--exit-code', '--quiet', '--', 'tasks/desert-rv/unity/Assets'], cwd=ROOT)
    output = TASK / 'evidence/android'
    output.mkdir(parents=True, exist_ok=False)
    shutil.copyfile(apk, output / 'DesertRV.apk')
    (output / 'build-receipt.json').write_text(json.dumps(native, indent=2) + '\n')
    independent = dict(base, schema='desert-rv-apk-verification/v1', **result,
                       projectPath='tasks/desert-rv/unity', nativeReceiptSha256=sha(receipt),
                       editModeTestsPassed=int(count), originalTestXmlSha256=xml_hash,
                       playModeTestsPassed=int(play_count), originalPlayModeTestXmlSha256=play_hash,
                       nativeReceiptFieldsVerified=True, zipCrcAndArm64Il2cppVerified=True,
                       deviceExecution='NOT_RUN', gameAcceptance='NOT_COMPLETE_GAME')
    (output / 'verification.json').write_text(json.dumps(independent, indent=2) + '\n')
    (output / 'SHA256SUMS').write_text(''.join(sha(p) + '  ' + p.name + '\n' for p in sorted(output.iterdir())))
    print('New APK/receipt/scene bytes and current run identity verified; device execution NOT_RUN.')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('mode', choices=['guard', 'tests', 'playmode', 'apk'])
    args = parser.parse_args()
    if args.mode == 'guard':
        guard()
    elif args.mode in {'tests', 'playmode'}:
        mode = 'editmode' if args.mode == 'tests' else 'playmode'
        result = inspect_tests(TASK / ('artifacts/tests' if mode == 'editmode' else 'artifacts/playmode'), mode)
        with open(os.environ['GITHUB_OUTPUT'], 'a') as f:
            for output, key in [('test_commit', 'commit'), ('test_run_id', 'runId'), ('test_run_attempt', 'runAttempt'), ('test_source_state_sha256', 'sourceStateSha256')]:
                f.write(output + '=' + result[key] + '\n')
            f.write('test_count=' + str(result['passed']) + '\n')
            f.write('test_xml_sha256=' + result['originalXmlSha256'] + '\n')
        print('Exact native test inventory passed; safe evidence saved.')
    else:
        verify_apk()


if __name__ == '__main__':
    main()
