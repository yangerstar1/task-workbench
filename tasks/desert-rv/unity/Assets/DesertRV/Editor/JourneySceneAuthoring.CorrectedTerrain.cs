        static Material RequireCorrectedBeaconMaterial(Material material,bool settled)
        {
            if(!material||!EditorUtility.IsPersistent(material)||!AssetDatabase.IsMainAsset(material)||
                AssetDatabase.GetAssetPath(material)!=CorrectedBeaconMaterial||!material.shader||
                material.shader.name!="Universal Render Pipeline/Lit"||!material.shader.isSupported||ShaderUtil.ShaderHasError(material.shader)||
                !material.GetColor("_BaseColor").Equals(new Color(1,.76f,.38f))||
                !material.GetColor("_EmissionColor").Equals(new Color(1,.76f,.38f)*2.5f)||
                material.GetTexture("_EmissionMap")||material.GetTexture("_BaseMap")||
                material.GetFloat("_Smoothness")!=.12f||material.GetFloat("_Metallic")!=0||
                material.GetFloat("_Surface")!=0||material.GetFloat("_ZWrite")!=1||
                material.shaderKeywords.Any(k=>k!="_EMISSION"))
                throw new InvalidOperationException("Warm beacon diffuser lost its exact authored material identity or HDR emission.");
            if(settled&&(material.globalIlluminationFlags!=MaterialGlobalIlluminationFlags.BakedEmissive||
                !material.IsKeywordEnabled("_EMISSION")||EditorUtility.IsDirty(material)))
                throw new InvalidOperationException("Warm beacon emission/GI keyword state is inconsistent or dirty.");
            return material;
        }
        static string ValidateCorrectedBeaconWithInstalledLit(Material material)
        {
            // Use the installed shader's complete validator, including its Lit/detail callbacks.
            // MaterialEditor initializes customShaderGUI in OnEnable; no preview/GUI is rendered.
            var editor=global::UnityEditor.Editor.CreateEditor(material) as MaterialEditor;
            try
            {
                if(!editor||editor.customShaderGUI==null||
                    editor.customShaderGUI.GetType().FullName!="UnityEditor.Rendering.Universal.ShaderGUI.LitShader")
                    throw new InvalidOperationException("Expected the installed URP Lit ShaderGUI validator.");
                editor.customShaderGUI.ValidateMaterial(material);
                return editor.customShaderGUI.GetType().FullName;
            }
            finally{if(editor)Object.DestroyImmediate(editor);}
        }
        static string SettleCorrectedBeaconEmissionCycle()
        {
            var material=RequireCorrectedBeaconMaterial(AssetDatabase.LoadAssetAtPath<Material>(CorrectedBeaconMaterial),false);
            string validator=ValidateCorrectedBeaconWithInstalledLit(material);
            // GUID-level save includes URP's AssetVersion subasset, unlike saving just the main Material.
            AssetDatabase.SaveAssetIfDirty(AssetDatabase.GUIDFromAssetPath(CorrectedBeaconMaterial));
            AssetDatabase.ImportAsset(CorrectedBeaconMaterial,ImportAssetOptions.ForceUpdate|ImportAssetOptions.ForceSynchronousImport);
            AssetDatabase.SaveAssetIfDirty(AssetDatabase.GUIDFromAssetPath(CorrectedBeaconMaterial));
            RequireCorrectedBeaconMaterial(AssetDatabase.LoadAssetAtPath<Material>(CorrectedBeaconMaterial),true);
            var objects=AssetDatabase.LoadAllAssetsAtPath(CorrectedBeaconMaterial);
            if(objects.Length==0||objects.Any(item=>!item||!EditorUtility.IsPersistent(item)||EditorUtility.IsDirty(item)))
                throw new InvalidOperationException("Warm beacon material or native subasset remains dirty after explicit save/import.");
            return validator;
        }
        static string CorrectedBeaconNonEmissionBytes(byte[] bytes)
        {
            if(bytes.Length==0||bytes.Length>65536)throw new InvalidOperationException("Warm beacon material exceeds bounded serialization.");
            string text=new UTF8Encoding(false,true).GetString(bytes);
            var flags=new Regex(@"(?m)^  m_LightmapFlags: [0-7]\r?$",RegexOptions.CultureInvariant);
            var keyword=new Regex(@"(?m)^  m_ValidKeywords:(?: \[\]|\r?\n  - _EMISSION)\r?$",RegexOptions.CultureInvariant);
            if(flags.Matches(text).Count!=1||keyword.Matches(text).Count!=1)
                throw new InvalidOperationException("Missing/ambiguous warm beacon emission fields.");
            // Only these two typed authored fields may change. Version, shader, colors, aliases,
            // textures, passes, render state and every other serialized byte remain compared.
            return keyword.Replace(flags.Replace(text,"  m_LightmapFlags: <authored-emission>"),"  m_ValidKeywords: <authored-emission>");
        }
        static void FinalizeCorrectedBeaconEmission()
        {
            var authored=SnapshotCorrectedTerrainGenerated();byte[] original=File.ReadAllBytes(CorrectedBeaconMaterial);
            string meta=HashFile(CorrectedBeaconMaterial+".meta");
            var material=RequireCorrectedBeaconMaterial(AssetDatabase.LoadAssetAtPath<Material>(CorrectedBeaconMaterial),false);
            int oldFlags=(int)material.globalIlluminationFlags;bool oldKeyword=material.IsKeywordEnabled("_EMISSION");
            Color oldEmission=material.GetColor("_EmissionColor");
            if(material.globalIlluminationFlags!=MaterialGlobalIlluminationFlags.None&&
                material.globalIlluminationFlags!=MaterialGlobalIlluminationFlags.EmissiveIsBlack&&
                material.globalIlluminationFlags!=MaterialGlobalIlluminationFlags.BakedEmissive)
                throw new InvalidOperationException("Refuse to replace an unexpected warm beacon GI mode.");
            // This is the sole authored correction. Keep the original nonzero HDR color unchanged.
            material.globalIlluminationFlags=MaterialGlobalIlluminationFlags.BakedEmissive;
            EditorUtility.SetDirty(material);
            string validator=SettleCorrectedBeaconEmissionCycle();
            byte[] stable=File.ReadAllBytes(CorrectedBeaconMaterial);
            if(CorrectedBeaconNonEmissionBytes(original)!=CorrectedBeaconNonEmissionBytes(stable))
                throw new InvalidOperationException("Warm beacon save changed bytes beyond its GI flag/emission keyword.");
            if(SettleCorrectedBeaconEmissionCycle()!=validator)throw new InvalidOperationException("Installed Lit validator changed between cycles.");
            if(!stable.SequenceEqual(File.ReadAllBytes(CorrectedBeaconMaterial))||HashFile(CorrectedBeaconMaterial+".meta")!=meta)
                throw new InvalidOperationException("Warm beacon material/meta is not stable across two validation/save/import cycles.");
            var settled=SnapshotCorrectedTerrainGenerated();
            if(!authored.Keys.OrderBy(p=>p,StringComparer.Ordinal).SequenceEqual(settled.Keys.OrderBy(p=>p,StringComparer.Ordinal))||authored.Any(row=>row.Key!=CorrectedBeaconMaterial&&settled[row.Key]!=row.Value))
                throw new InvalidOperationException("Warm beacon emission correction changed another generated file.");
            material=RequireCorrectedBeaconMaterial(AssetDatabase.LoadAssetAtPath<Material>(CorrectedBeaconMaterial),true);
            Debug.Log("CORRECTED_BEACON_EMISSION_LIFECYCLE "+JsonUtility.ToJson(new CorrectedBeaconEmissionEvidence{
                path=CorrectedBeaconMaterial,beforeSha256=authored[CorrectedBeaconMaterial],savedSha256=HashFile(CorrectedBeaconMaterial),metaSha256=meta,
                validator=validator,beforeGIFlags=oldFlags,afterGIFlags=(int)material.globalIlluminationFlags,
                beforeEmissionKeyword=oldKeyword,afterEmissionKeyword=material.IsKeywordEnabled("_EMISSION"),beforeEmissionColor=oldEmission,afterEmissionColor=material.GetColor("_EmissionColor")}));
        }
