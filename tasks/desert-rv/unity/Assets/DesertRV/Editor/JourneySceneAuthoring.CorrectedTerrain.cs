                            mainTexAsset=AssetDatabase.GetAssetPath(material.GetTexture("_MainTex")),mainTexSha256=HashFile(AssetDatabase.GetAssetPath(material.GetTexture("_MainTex"))),actual=ReadDiffuseComparisonMaterial(material)});
                    }
                    finally{Object.DestroyImmediate(baseline);}
                }
                var after=SnapshotCorrectedTerrainGenerated();
                RequireCorrectedTerrainGeneratedDelta(before,after);
                report=new CorrectedTerrainReport{correctedDiffuse=importer,materials=records.ToArray(),allOtherGeneratedBytesPreserved=true,
