            }
            finally
            {
                try{RestoreSceneSetup(setup);}
                finally{VerifyProtectedFiles(protectedFiles);}
            }
            RequireCorrectedTerrainSavedBytes(report);
            WriteCorrectedTerrainAuditPhase("freeze",report);
