        public static void AuthorCorrectedTerrainCandidateScenes()
        {
            if(File.Exists(CorrectedTerrainReceipt))throw new IOException("Refuse stale corrected-terrain receipt.");
            var protectedFiles=SnapshotProtectedFiles();
            AuthorCandidateScenes();
            var setup=EditorSceneManager.GetSceneManagerSetup();
            CorrectedTerrainReport report=null;
            try
            {
                EditorSceneManager.OpenScene(BootstrapPath,OpenSceneMode.Single);
                var scene=EditorSceneManager.OpenScene(RegionPaths[0],OpenSceneMode.Additive);
                SceneManager.SetActiveScene(scene);
                FinalizeCorrectedBeaconEmission();
                // First settle Unity's legitimate fresh-material serialization/version normalization.
                // Freeze all generated bytes only after this original-diffuse save/import cycle.
                foreach(string path in CorrectedTerrainMaterials)
                {
                    var material=AssetDatabase.LoadAssetAtPath<Material>(path);
                    if(!material||AssetDatabase.GetAssetPath(material.GetTexture("_BaseMap"))!=ComparisonOriginalDiffuse)
                        throw new InvalidOperationException("Correction must start with newly authored original terrain: "+path);
                    EditorUtility.SetDirty(material);
                }
                AssetDatabase.SaveAssets();
                foreach(string path in CorrectedTerrainMaterials)
                    AssetDatabase.ImportAsset(path,ImportAssetOptions.ForceUpdate|ImportAssetOptions.ForceSynchronousImport);
                AssetDatabase.SaveAssets();
                var before=SnapshotCorrectedTerrainGenerated();
                var records=new List<CorrectedTerrainMaterial>();
                // No asset object is retained across a scene transition. Load after the final OpenScene.
                var corrected=LoadVerifiedCorrectedTerrain(out var importer);
                string originalGuid=AssetDatabase.AssetPathToGUID(ComparisonOriginalDiffuse);
                foreach(string path in CorrectedTerrainMaterials)
                {
                    byte[] original=File.ReadAllBytes(path);
                    var material=AssetDatabase.LoadAssetAtPath<Material>(path);
                    var baseline=new Material(material){hideFlags=HideFlags.HideAndDontSave};
                    try
                    {
                        material.SetTexture("_BaseMap",corrected);material.SetTexture("_MainTex",corrected);
                        AssertCorrectedTerrainMaterial(material,baseline,corrected);
                        EditorUtility.SetDirty(material);AssetDatabase.SaveAssets();
                        AssetDatabase.ImportAsset(path,ImportAssetOptions.ForceUpdate|ImportAssetOptions.ForceSynchronousImport);
                        material=AssetDatabase.LoadAssetAtPath<Material>(path);
                        AssertCorrectedTerrainMaterial(material,baseline,corrected);
                        byte[] firstSaved=File.ReadAllBytes(path);
                        RequireOnlyCorrectedAlbedoReferences(original,firstSaved,originalGuid,importer.guid);
                        // URP synchronizes _MainTex with _BaseMap on material validation. Explicitly persist
                        // both aliases, then prove a second save/import round cannot change any bytes.
                        EditorUtility.SetDirty(material);AssetDatabase.SaveAssets();
                        AssetDatabase.ImportAsset(path,ImportAssetOptions.ForceUpdate|ImportAssetOptions.ForceSynchronousImport);
                        material=AssetDatabase.LoadAssetAtPath<Material>(path);
                        AssertCorrectedTerrainMaterial(material,baseline,corrected);
                        if(!firstSaved.SequenceEqual(File.ReadAllBytes(path)))throw new InvalidOperationException("Corrected material save/import is not byte-stable.");
                        records.Add(new CorrectedTerrainMaterial{path=path,originalSerializedBase64=Convert.ToBase64String(original),
                            originalSha256=before[path],savedSha256=HashFile(path),onlyAlbedoReferencesChanged=true,saveImportCycles=2,secondSaveImportBytesStable=true,
                            baseMapAsset=AssetDatabase.GetAssetPath(material.GetTexture("_BaseMap")),
