        static void AssertCorrectedTerrainMaterial(Material material,Material original,Texture2D diffuse)
        {
            if(material.shader!=original.shader||material.renderQueue!=original.renderQueue||material.enableInstancing!=original.enableInstancing||
                material.doubleSidedGI!=original.doubleSidedGI||material.globalIlluminationFlags!=original.globalIlluminationFlags||
                !material.shaderKeywords.OrderBy(k=>k,StringComparer.Ordinal).SequenceEqual(original.shaderKeywords.OrderBy(k=>k,StringComparer.Ordinal))||
                !material.IsKeywordEnabled("_NORMALMAP")||AssetDatabase.GetAssetPath(material.GetTexture("_BumpMap"))!=ComparisonNormal||
                Mathf.Abs(material.GetFloat("_BumpScale")-.035f)>.000001f||material.GetTexture("_BaseMap")!=diffuse||material.GetTexture("_MainTex")!=diffuse)
                throw new InvalidOperationException("Corrected terrain changed shader, keywords, normal, or either albedo alias.");
            for(int i=0;i<original.passCount;i++)
                if(material.GetShaderPassEnabled(original.GetPassName(i))!=original.GetShaderPassEnabled(original.GetPassName(i)))
                    throw new InvalidOperationException("Corrected terrain changed shader pass state.");
            for(int i=0;i<original.shader.GetPropertyCount();i++)
            {
                string property=original.shader.GetPropertyName(i);bool same;
                switch(original.shader.GetPropertyType(i))
                {
                    case ShaderPropertyType.Color:same=material.GetColor(property)==original.GetColor(property);break;
                    case ShaderPropertyType.Vector:same=material.GetVector(property)==original.GetVector(property);break;
                    case ShaderPropertyType.Float:case ShaderPropertyType.Range:same=material.GetFloat(property)==original.GetFloat(property);break;
                    case ShaderPropertyType.Int:same=material.GetInteger(property)==original.GetInteger(property);break;
                    case ShaderPropertyType.Texture:
                        same=material.GetTexture(property)==(property=="_BaseMap"||property=="_MainTex"?diffuse:original.GetTexture(property))&&
                            material.GetTextureScale(property)==original.GetTextureScale(property)&&material.GetTextureOffset(property)==original.GetTextureOffset(property);break;
                    default:throw new InvalidOperationException("Unrecognized corrected terrain shader property: "+property);
                }
                if(!same)throw new InvalidOperationException("Corrected terrain changed material property: "+property);
            }
        }

        static Dictionary<string,string> SnapshotCorrectedTerrainGenerated()
        {
            return Directory.GetFiles(Folder,"*",SearchOption.AllDirectories).Select(p=>p.Replace('\\','/'))
                .Concat(new[]{Folder+".meta"}).OrderBy(p=>p,StringComparer.Ordinal).ToDictionary(p=>p,HashFile);
        }
        static void RequireCorrectedTerrainGeneratedDelta(Dictionary<string,string> before,Dictionary<string,string> after)
        {
            if(!before.Keys.OrderBy(p=>p,StringComparer.Ordinal).SequenceEqual(after.Keys.OrderBy(p=>p,StringComparer.Ordinal)))
                throw new InvalidOperationException("Corrected terrain changed generated asset membership.");
            var changed=before.Keys.Where(p=>before[p]!=after[p]).OrderBy(p=>p,StringComparer.Ordinal).ToArray();
            if(!changed.SequenceEqual(CorrectedTerrainMaterials.OrderBy(p=>p,StringComparer.Ordinal)))
                throw new InvalidOperationException("Only saved Sand/Dune material payloads may change; scenes, meshes, metadata and other materials must be byte-identical.");
        }
        static void RequireOnlyCorrectedAlbedoReferences(byte[] before,byte[] after,string originalGuid,string correctedGuid)
        {
            // Exact UTF-8 bytes: only the two URP albedo-alias GUIDs may differ; every other serialized field is frozen.
            string text=new UTF8Encoding(false,true).GetString(before);
            var pattern=new Regex(@"(?m)^(    - _(BaseMap|MainTex):\r?\n        m_Texture: \{fileID: 2800000, guid: )"+Regex.Escape(originalGuid)+@"(, type: 3\})\r?$",RegexOptions.CultureInvariant);
            if(pattern.Matches(text).Count!=2||pattern.Matches(text).Cast<Match>().Select(m=>m.Groups[2].Value).Distinct().Count()!=2)
                throw new InvalidOperationException("Missing/duplicate original serialized albedo aliases.");
            string expected=pattern.Replace(text,m=>m.Value.Replace(originalGuid,correctedGuid));
            if(!new UTF8Encoding(false,true).GetBytes(expected).SequenceEqual(after))
                throw new InvalidOperationException("A saved material byte other than the two albedo-alias texture GUIDs changed.");
        }
        static CorrectedTerrainBinding[] ReadSavedCorrectedTerrainBindings(CorrectedTerrainReport report)
        {
            var result=new List<CorrectedTerrainBinding>();
            for(int region=1;region<=3;region++)
            {
                EditorSceneManager.OpenScene(BootstrapPath,OpenSceneMode.Single);
                var scene=EditorSceneManager.OpenScene(RegionPaths[region-1],OpenSceneMode.Additive);SceneManager.SetActiveScene(scene);
                // Assets may have been unloaded by OpenScene(Single); reload only after both scene transitions.
                var corrected=LoadVerifiedCorrectedTerrain(out var imported);
                if(JsonUtility.ToJson(imported)!=JsonUtility.ToJson(report.correctedDiffuse))throw new InvalidOperationException("Corrected import identity changed on scene reload.");
                var binding=Components<RegionBinding>(scene).Single();
                if(region==3)RecordCorrectedBeaconEmissionBinding(binding);
                var terrain=binding.GetComponentsInChildren<Renderer>(true).Where(r=>r.enabled&&r.sharedMaterial&&
                    CorrectedTerrainMaterials.Contains(AssetDatabase.GetAssetPath(r.sharedMaterial))).ToArray();
                if(terrain.Length!=3||terrain.Any(r=>r.sharedMaterials.Length!=1))throw new InvalidOperationException("Expected exactly three saved single-material terrain renderers per region.");
                foreach(var role in comparisonTerrainRoles)
                {
                    var renderer=terrain.Single(r=>r.name=="EnvironmentV4 "+role[0]);var mesh=renderer.GetComponent<MeshFilter>();
                    string materialPath=PolishGenerated+"/Surface-"+role[1]+".mat",meshPath=PolishGenerated+"/R"+region+"-"+role[0]+".asset";
                    if(renderer.gameObject.scene!=scene||renderer.transform.parent!=binding.transform||!mesh||!mesh.sharedMesh||
                       AssetDatabase.GetAssetPath(mesh.sharedMesh)!=meshPath||AssetDatabase.GetAssetPath(renderer.sharedMaterial)!=materialPath||
                       renderer.sharedMaterial!=AssetDatabase.LoadAssetAtPath<Material>(materialPath)||renderer.sharedMaterial.GetTexture("_BaseMap")!=corrected||renderer.sharedMaterial.GetTexture("_MainTex")!=corrected)
                        throw new InvalidOperationException("Saved corrected terrain object/parent/scene/mesh/material/BaseMap binding differs.");
                    var expected=report.materials.Single(m=>m.path==materialPath);
                    if(JsonUtility.ToJson(ReadDiffuseComparisonMaterial(renderer.sharedMaterial))!=JsonUtility.ToJson(expected.actual))
                        throw new InvalidOperationException("Persisted terrain material properties differ after scene reload.");
                    result.Add(new CorrectedTerrainBinding{region=region,objectName=renderer.name,scenePath=scene.path,meshAsset=meshPath,
                        materialAsset=materialPath,baseMapAsset=AssetDatabase.GetAssetPath(renderer.sharedMaterial.GetTexture("_BaseMap")),
                        baseMapSha256=HashFile(AssetDatabase.GetAssetPath(renderer.sharedMaterial.GetTexture("_BaseMap"))),
                        mainTexAsset=AssetDatabase.GetAssetPath(renderer.sharedMaterial.GetTexture("_MainTex")),
                        mainTexSha256=HashFile(AssetDatabase.GetAssetPath(renderer.sharedMaterial.GetTexture("_MainTex")))});
                }
            }
            return result.ToArray();
        }
        static void RequireCorrectedTerrainSavedBytes(CorrectedTerrainReport report)
        {
            if(report==null||report.materials==null||report.materials.Length!=2||report.generatedFiles==null||!report.allOtherGeneratedBytesPreserved)
                throw new InvalidOperationException("Incomplete corrected saved-asset receipt.");
            var current=SnapshotCorrectedTerrainGenerated();
            if(!report.generatedFiles.Select(r=>r.path).OrderBy(p=>p,StringComparer.Ordinal).SequenceEqual(current.Keys.OrderBy(p=>p,StringComparer.Ordinal)))
                throw new InvalidOperationException("Generated membership changed after corrected authoring.");
            foreach(var row in report.generatedFiles)
                if(current[row.path]!=row.afterSha256||(!CorrectedTerrainMaterials.Contains(row.path)&&row.beforeSha256!=row.afterSha256))
                    throw new InvalidOperationException("Frozen saved asset changed: "+row.path);
            foreach(var row in report.materials)
            {
                if(!CorrectedTerrainMaterials.Contains(row.path)||!row.onlyAlbedoReferencesChanged||!row.secondSaveImportBytesStable||row.saveImportCycles!=2||HashFile(row.path)!=row.savedSha256)
                    throw new InvalidOperationException("Wrong persisted corrected material identity.");
                RequireOnlyCorrectedAlbedoReferences(Convert.FromBase64String(row.originalSerializedBase64),File.ReadAllBytes(row.path),
                    AssetDatabase.AssetPathToGUID(ComparisonOriginalDiffuse),report.correctedDiffuse.guid);
            }
        }
