        void HidePresentation(GameObject owner)
        {
            if(!hiddenPresentationObjects.ContainsKey(owner))hiddenPresentationObjects.Add(owner,owner.activeSelf);
            owner.SetActive(false);
        }
        void IsolateLoadedPresentations()
        {
            // Find owned G3 objects across all loaded scenes (also inactive ones).
            // Disable the component's own subtree, never an arbitrary ancestor
            // that could also own the Unity Test Framework controller.
            foreach(var bootstrap in Object.FindObjectsByType<G3SliceBootstrap>(FindObjectsInactive.Include,FindObjectsSortMode.None))
            {
                var owner=bootstrap.gameObject;
                if(owner.scene.IsValid()&&owner.scene.isLoaded)HidePresentation(owner);
            }
            // G0 has no G3 bootstrap component; retain only its exact owned names.
            for(int i=0;i<SceneManager.sceneCount;i++)
            {
                var loaded=SceneManager.GetSceneAt(i);if(!loaded.isLoaded)continue;
                foreach(var root in loaded.GetRootGameObjects())if(LegacyProbeRootNames.Contains(root.name))HidePresentation(root);
            }
        }
